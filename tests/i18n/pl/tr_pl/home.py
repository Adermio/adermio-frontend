# Âge des témoignages : 1 rok / 2–4 lata (sauf 12–14) / 5+ lat (22 lata, 24 lata, 42 lata ; 27 lat, 31 lat…)
def _wiek(m):
    n = int(m.group(1))
    if n == 1:
        w = 'rok'
    elif n % 10 in (2, 3, 4) and n % 100 not in (12, 13, 14):
        w = 'lata'
    else:
        w = 'lat'
    return '>' + str(n) + ' ' + w + '<'
